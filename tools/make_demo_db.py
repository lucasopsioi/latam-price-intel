def title_for(brand: str, model: str, cat: str, ram, rom, color, lang: str) -> str:
    col = COLORS_PT.get(color, color) if lang == "pt" else color
    if cat in ("phone", "tablet") and ram and rom:
        return f"{brand} {model} {ram}GB+{rom}GB {col}"
    if cat == "phone":
        return f"Celular {brand} {model} {col}"
    if cat == "tablet":
        return f"Tablet {brand} {model} {col}"
    if cat == "audio":
        return f"Audifonos {brand} {model} {col}" if lang != "pt" else f"Fone {brand} {model} {col}"
    return f"Smartwatch {brand} {model} {col}"


