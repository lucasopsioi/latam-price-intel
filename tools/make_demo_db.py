    # ------------------------------------------------ price series

    def _plan_series(self, usd: float, launch_off, cc: str) -> list[float | None]:
        """Daily multiplier on the base price (None = not on shelf yet)."""
        n = self.days
        rng = self.rng
        mult = [1.0] * n
        appear = 0
        if launch_off is not None:
            appear = max(0, n - launch_off - rng.randint(0, 6))   # on shelf a few days after global launch
            for i in range(appear, min(n, appear + rng.randint(8, 16))):
                mult[i] = 1.08                                     # launch premium
        # 0-2 promo windows
        for _ in range(rng.choice([0, 0, 1, 1, 2])):
            s = rng.randint(appear, max(appear, n - 6))
            length = rng.randint(4, 12)
            off = rng.choice([0.05, 0.06, 0.08, 0.10, 0.12, 0.15, 0.18, 0.22, 0.25])
            for i in range(s, min(n, s + length)):
                mult[i] = min(mult[i], 1.0 - off)
        # occasional permanent rise or cut (step)
        # one permanent step (rise or cut) on ~36% of lines - the factor is drawn ONCE,
        # otherwise every day after the step would re-roll and look like daily jitter
        roll = rng.random()
        if roll < 0.36:
            s = rng.randint(appear + 5, n - 1) if n - 1 > appear + 5 else n - 1
            step = rng.choice([1.05, 1.07, 1.09, 1.12]) if roll < 0.18 else rng.choice([0.93, 0.95, 0.96])
            for i in range(s, n):
                mult[i] = mult[i] * step
        # mark days before launch as absent
        return [None if i < appear else round(m, 4) for i, m in enumerate(mult)]

