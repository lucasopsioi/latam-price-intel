# ---------------------------------------------------------------- main

def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Fill the app database with a synthetic demo dataset.")
    ap.add_argument("--seed", type=int, default=20260901, help="RNG seed (default 20260901)")
    ap.add_argument("--days", type=int, default=60, help="days of daily observations (default 60)")
    ap.add_argument("--end", default=None, help="last observation date YYYY-MM-DD (default: today)")
    ap.add_argument("--fresh", action="store_true", help="delete data/intel.db before building")
    args = ap.parse_args(argv)

    end = date.fromisoformat(args.end) if args.end else date.today()

    made = ensure_config_files()
    for p in made:
        print(f"created {p}")

    from app import config, db, products, trends   # noqa: E402  (after config files exist)

    if args.fresh:
        for suffix in ("", "-wal", "-shm"):
            p = Path(str(config.DB_PATH) + suffix)
            if p.exists():
                p.unlink()
        print(f"removed {config.DB_PATH}")

    db.init_db()
    existing = db.q1("SELECT COUNT(*) c FROM price_obs")["c"]
    if existing:
        print(f"database already holds {existing} price observations: {config.DB_PATH}")
        print("re-run with --fresh to rebuild the demo dataset from scratch")
        return 1

    print(f"building synthetic dataset: seed={args.seed} days={args.days} end={end}")
    b = DemoBuilder(args.seed, end, args.days)
    print("[1/7] dimensions (brands, channels, fx)");   b.dims(db)
    print("[2/7] products");                            b.products(db, products)
    print("[3/7] daily price observations + moves");    b.observations(db)
    print("[4/7] launch events, intel feed, signals");  b.launches(db); b.intel(db)
    print("[5/7] reviews and aspect tags");             b.voc(db)
    print("[6/7] competitor matches, watchlist, alerts")
    b.matches(db); b.watch_and_alerts(db, trends)
    print("[7/7] weekly brief (facts-only, no LLM)");   b.weekly(db)

    print("\nrows written:")
    for k, v in b.counts.items():
        print(f"  {k:<18} {v}")
    print(f"\ndatabase: {config.DB_PATH}")
    print("next:     python main.py serve   ->  open http://127.0.0.1:8765")
    return 0


if __name__ == "__main__":
    sys.exit(main())
