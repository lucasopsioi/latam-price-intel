def _deep_merge(base: dict, override: dict) -> dict:
    out = dict(base)
    for k, v in (override or {}).items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def ensure_config_files() -> list[str]:
    """Create config/runtime.yaml and config/my_products.csv when missing."""
    import yaml

    made = []
    cfg_dir = ROOT / "config"
    rt = cfg_dir / "runtime.yaml"
    if not rt.exists():
        example = cfg_dir / "runtime.example.yaml"
        base = {}
        if example.exists():
            with open(example, "r", encoding="utf-8") as f:
                base = yaml.safe_load(f) or {}
        merged = _deep_merge(base, RUNTIME_DEMO_OVERRIDES)
        with open(rt, "w", encoding="utf-8") as f:
            f.write("# Generated by tools/make_demo_db.py - demo settings, no tokens.\n"
                    "# Scheduling / Telegram / phone sync are OFF; turn them on only\n"
                    "# when you configure real credentials in the Settings page.\n")
            yaml.safe_dump(merged, f, allow_unicode=True, sort_keys=False)
        made.append(str(rt))

    csv_path = cfg_dir / "my_products.csv"
    if not csv_path.exists():
        example = cfg_dir / "my_products.example.csv"
        if example.exists():
            shutil.copyfile(example, csv_path)
            made.append(str(csv_path))
    return made


